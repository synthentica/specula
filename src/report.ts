// report: renders analysis/REPORT.md from correlation.json and fingerprint.json.
// Every claim keeps its evidence reference; the "Not determined" section lists the gaps.
//
//   node src/report.ts --target vikunja

import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { loadFlows } from './lib/captures.ts';
import { loadTarget, printSummary } from './lib/target.ts';

const { values: args } = parseArgs({ options: { target: { type: 'string' } } });
if (!args.target) {
  process.stderr.write('Usage: node src/report.ts --target <name>\n');
  process.exit(2);
}
const { config, paths } = await loadTarget(args.target);
const read = async (file: string) => {
  const path = join(paths.analysis, file);
  if (!existsSync(path)) throw new Error(`Missing analysis/${file}. Run ${file.replace('.json', '')} first.`);
  return JSON.parse(await readFile(path, 'utf8'));
};
const correlation = await read('correlation.json');
const fp = await read('fingerprint.json');
const flows = await loadFlows(paths);

interface Evidence {
  ref: string;
  detail: string;
}
interface Finding {
  claim: string;
  confidence: string;
  evidence: Evidence[];
  value?: unknown;
}

const md: string[] = [];
const ev = (evidence: Evidence[]) => (evidence.length ? evidence.map((e) => `\`${e.ref}\`${e.detail ? ` (${e.detail.replaceAll('|', '\\|').slice(0, 140)})` : ''}`).join('; ') : '—');
const findingRows = (findings: Finding[]) => {
  if (!findings.length) return ['_None observed._', ''];
  return ['| Claim | Confidence | Evidence |', '|---|---|---|', ...findings.map((f) => `| ${f.claim.replaceAll('|', '\\|')} | ${f.confidence} | ${ev(f.evidence)} |`), ''];
};

md.push(`# ${config.name}: evidence report`, '');
md.push(`Generated by specula from ${flows.length} recorded flows (${flows.map((f) => f.name).join(', ')}).`);
md.push('Each claim links to a HAR entry (`capture/<flow>.har#entries[i]`), an event line (`capture/<flow>.events.jsonl:n`) or a bundle position (`capture/sources/<file>:line`). Backend behaviour is inferred only from what the browser received.', '');

md.push('## Stack', '', ...findingRows([...fp.frontend, ...fp.libraries]));
md.push('## Backend and API style', '', ...findingRows(fp.backend));
md.push('## Authentication', '', ...findingRows(fp.auth));
// GraphQL: one URL, many operations. spec/graphql.json (from infer-api) lists them; failures reported in-band count too.
const graphqlFile = join(paths.spec, 'graphql.json');
if (existsSync(graphqlFile)) {
  type Op = { name: string; type: string; count: number; flows: string[]; errors?: { message?: string; code?: string }[]; failures?: Record<string, unknown>[] };
  const ops = (JSON.parse(await readFile(graphqlFile, 'utf8')) as { operations: Op[] }).operations;
  const failure = (o: Op) =>
    [...(o.errors ?? []).map((e) => `error ${e.code ?? ''}: ${e.message ?? ''}`.trim()), ...(o.failures ?? []).map((f) => `in-band ${Object.entries(f).filter(([k]) => k !== 'path' && k !== 'message').map(([k, v]) => `${k}=${v}`).join(' ')}`)].join('; ');
  md.push('## GraphQL operations', '');
  md.push(`${ops.length} operations observed (full documents, variables and result shapes in \`spec/graphql.json\`). Operations without a client-side name are named by their type and root fields. Failures the server reported inside a 200 response are listed with their codes.`, '');
  md.push('| Operation | Calls | Flows | Failures seen |', '|---|---|---|---|', ...ops.map((o) => `| \`${o.name}\` | ${o.count} | ${o.flows.join(', ')} | ${failure(o).replaceAll('|', '\\|') || '—'} |`), '');
}
md.push('## Realtime', '');
md.push(...findingRows(fp.realtime));
for (const r of fp.realtime as Finding[]) {
  const value = r.value as { messages?: { message: string; count: number; keys: string[] }[]; subscribedEvents?: string[] } | null;
  if (!value?.messages) continue;
  md.push(`Messages on \`${r.claim.replace('WebSocket ', '')}\`:`, '', ...value.messages.map((m) => `- \`${m.message}\` ×${m.count}, keys: ${m.keys.join(', ')}`));
  if (value.subscribedEvents) md.push(`- subscribed events: ${value.subscribedEvents.map((e) => `\`${e}\``).join(', ')}`);
  md.push('');
}
md.push('## Feature switches', '', ...findingRows(fp.flags));
for (const f of fp.flags as Finding[]) {
  if (f.value && typeof f.value === 'object') md.push(`${f.claim}:`, '', ...Object.entries(f.value as Record<string, boolean>).map(([k, v]) => `- \`${k}\`: ${v}`), '');
}
md.push('## Third parties', '', ...findingRows(fp.thirdParties));

md.push('## Features: action → requests → code', '');
md.push('Code locations are the frame that issued the request (`call site`), the first feature-specific frame (`origin`) and the UI component on the async chain. Without source maps these point into minified bundles. Where the browser received a public source map, the original files along the chain are listed instead, innermost first.', '');
for (const flow of correlation.flows) {
  md.push(`### ${flow.flow}`, '');
  const rows = [];
  for (const action of flow.actions) {
    if (!action.requests.length) continue;
    const label = action.kind === 'navigate' ? `navigate ${new URL(action.url).pathname}` : `${action.kind} "${action.target?.name ?? action.target?.selector}"${action.key ? ` (${action.key})` : ''}`;
    for (const r of action.requests) {
      if (r.resourceType !== 'Fetch' && r.resourceType !== 'XHR' && r.resourceType !== 'WebSocket') continue;
      const original = r.sourceChain?.map((f: { source: string; line: number }) => `\`${f.source}:${f.line}\``).join(' ← ');
      const where = original ? `source ${original}` : [r.origin && `origin ${r.origin.functionName || '(anonymous)'} @ \`${r.origin.file ?? r.origin.url}:${r.origin.lineNumber + 1}\``, r.component && `component ${r.component.url.split('/').pop()?.replace(/-[\w-]{8}\.js$/, '')}`]
        .filter(Boolean)
        .join(', ');
      rows.push(`| ${label.replaceAll('|', '\\|')} | \`${r.endpoint}\` ${r.status} | ${r.delayMs} ms, ${r.confidence} | ${where || '—'} | \`${r.entry}\` |`);
    }
  }
  md.push(rows.length ? ['| Action | Request | Delay, confidence | Code | Evidence |', '|---|---|---|---|---|', ...rows].join('\n') : '_No user-triggered API requests._', '');
  const background = flow.background.filter((b: { resourceType: string }) => b.resourceType === 'Fetch' || b.resourceType === 'XHR');
  if (background.length) md.push(`Not tied to an action: ${background.map((b: { endpoint: string; reason: string; entry: string }) => `\`${b.endpoint}\` (${b.reason}, \`${b.entry}\`)`).join('; ')}`, '');
}

md.push('## Frontend routes (from bundles)', '');
const routes = fp.routes as { route: string; name?: string; visited: boolean; ref: string }[];
md.push(`${routes.length} route definitions found, ${routes.filter((r) => r.visited).length} visited in the recorded flows.`, '');
md.push('| Route | Name | Visited | Evidence |', '|---|---|---|---|', ...routes.map((r) => `| \`${r.route}\` | ${r.name ?? ''} | ${r.visited ? 'yes' : ''} | \`${r.ref}\` |`), '');

const codePaths = fp.apiPathsInCode.paths as { path: string; observed: boolean; ref: string }[];
md.push('## API paths in code', '');
md.push(`${codePaths.length} API-shaped string literals in first-party bundles; ${codePaths.filter((p) => p.observed).length} of them were also observed in traffic. Unobserved paths are leads for more flows, not facts about the API.`, '');
md.push('<details><summary>Unobserved paths</summary>', '', ...codePaths.filter((p) => !p.observed).map((p) => `- \`${p.path}\` (\`${p.ref}\`)`), '', '</details>', '');

// ---- gaps --------------------------------------------------------------------------
const gaps: string[] = [];
gaps.push('Server-side logic (validation rules, permissions, side effects such as emails or webhooks) is only visible through responses; anything the flows did not trigger is unknown.');
const scriptIndex = existsSync(join(paths.sources, 'index.json')) ? Object.values(JSON.parse(await readFile(join(paths.sources, 'index.json'), 'utf8'))) as { url: string; sourceMapUrl?: string; sourceMapFile?: string }[] : [];
const mapsDeclared = scriptIndex.filter((r) => r.sourceMapUrl);
const mapsMissing = mapsDeclared.filter((r) => !r.sourceMapFile);
if (!correlation.sourceMaps) gaps.push('No public source maps: code locations point into minified bundles; original file names and functions are not recoverable from the browser.');
else if (mapsMissing.length) gaps.push(`${mapsMissing.length} of ${mapsDeclared.length} saved bundles name a source map the server does not serve (${[...new Set(mapsMissing.map((r) => new URL(r.url).host))].join(', ')}); code locations in them stay minified.`);
const unobserved = codePaths.filter((p) => !p.observed).length;
if (unobserved) gaps.push(`${unobserved} API paths appear in the frontend code but were never exercised (e.g. sharing, teams, attachments, migrations, admin). Their request/response shapes are unknown.`);
if ((fp.auth as Finding[]).some((f) => /No 401/.test(f.claim))) gaps.push('No 401 was observed, so the server\'s answer to an expired token and any retry after a refresh are inferred, not seen.');
const binaryOmitted = flows.reduce((n, f) => n + f.har.log.entries.filter((e) => /binary body/.test(e.response.content.comment ?? '')).length, 0);
if (binaryOmitted) gaps.push(`${binaryOmitted} binary response bodies were omitted because they cannot be redacted.`);
const sw = flows.some((f) => f.har.log.entries.some((e) => /\/sw\.js$|service-?worker/i.test(e.request.url)));
if (sw) gaps.push('A service worker is registered; requests it makes on its own (caching, background sync) are not recorded.');
for (const r of fp.realtime as Finding[]) {
  const value = r.value as { messages?: { message: string }[]; subscribedEvents?: string[] } | null;
  const received = new Set((value?.messages ?? []).filter((m) => m.message.startsWith('received')).map((m) => m.message.split(' ')[1]));
  const silent = (value?.subscribedEvents ?? []).filter((e) => !received.has(e));
  if (silent.length) gaps.push(`WebSocket events subscribed but never received during capture: ${silent.map((e) => `\`${e}\``).join(', ')}. Their payload shapes are unknown.`);
}
const lowConfidence = correlation.flows.flatMap((f: { actions: { requests: { confidence: string }[] }[] }) => f.actions.flatMap((a) => a.requests)).filter((r: { confidence: string }) => r.confidence === 'low').length;
if (lowConfidence) gaps.push(`${lowConfidence} action→request links are low confidence (time-based only).`);
md.push('## Not determined', '', ...gaps.map((g) => `- ${g}`), '');

await writeFile(join(paths.analysis, 'REPORT.md'), md.join('\n'));
printSummary({ ok: true, file: 'analysis/REPORT.md', sections: md.filter((l) => l.startsWith('## ')).length, gaps: gaps.length });
